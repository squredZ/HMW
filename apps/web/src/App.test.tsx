  await screen.findByLabelText('当前重点')
  fireEvent.change(screen.getByLabelText('当前重点'), {target:{value:'工作'}})
  fireEvent.click(screen.getByLabelText('向项目一成员发布'))
  fireEvent.change(screen.getByLabelText('项目'), {target:{value:'p1'}})
  fireEvent.change(screen.getByLabelText('周起始日期'), {target:{value:'2026-11-09'}})
  fireEvent.change(screen.getByLabelText('计划投入'), {target:{value:'4'}})
